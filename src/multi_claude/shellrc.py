"""`multi-claude completion --install / --uninstall`：把“现场生成补全”的设置写进 shell 配置文件（方案 feature-auto-completion）。

写进去的不是补全脚本本身，而是一段每次打开终端时调用 `multi-claude completion <shell>` 的设置，
所以不论以后用哪种方式升级，补全都跟着新版本走。install.sh 在安装、升级、卸载时各调用一次（带隐藏的 --auto）。

约束（误改的后果写在各处注释里）：
- 只动带开始 / 结束标记的那一段；块外的内容按字节原样保留，包括 BOM 和 \\r\\n；
- 写的是符号链接指向的真实文件，备份放在链接旁边，不放进 dotfiles 仓库；
- 用户执行过 `--uninstall` 后留下关闭标记，install.sh 不再把设置加回来。
"""

import os
import platform as py_platform
import re
import shutil
import stat
import subprocess
from typing import List, Mapping, NamedTuple, Optional, Tuple

from . import completion, platform
from .fsutil import atomic_write_bytes
from .statusline import _backup_path

BEGIN = "# >>> multi-claude completion >>>"
END = "# <<< multi-claude completion <<<"
# fish 的文件整个由本工具管理，按第一行这个标记识别；不比较全文，以后改了文件内容也认得出
FISH_MARKER = "# managed-by: multi-claude completion --install"
FISH_LINE = "type -q multi-claude; and multi-claude completion fish | source"
POWERSHELL_LINE = ("if (Get-Command multi-claude -ErrorAction SilentlyContinue) "
                   "{ multi-claude completion powershell | Out-String | Invoke-Expression }")
OFF_FILE = "completion-off"
POWERSHELL_HOSTS = ("powershell", "pwsh")
POWERSHELL_TIMEOUT = 10
_PS_QUERY = ("try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch {}; "
             "$PROFILE; Get-ExecutionPolicy")
_UTF8_BOM = b"\xef\xbb\xbf"
# 用户自己写的“现场生成”调用：有了就不再加块。旧快照（整段补全脚本）不算，它们只是一份过期副本
_LIVE_CALL = re.compile(r"[$<]\(\s*multi-claude completion|multi-claude completion \S+\s*\|")
_SNAPSHOT = "(generated by `multi-claude completion"
_ZSH_FALLBACK = re.compile(r"^_mc_bin=\$\{commands\[multi-claude\]:-'([^']*)'\}$")
_BASH_FALLBACK = re.compile(r"\|\| echo '([^']*)'\)$")
_NOT_UTF8 = "the file is not UTF-8; save it as UTF-8 and try again"


class ShellrcError(Exception):
    """单个配置文件处理失败（编码认不出、块损坏）；其它文件照常处理，最后退出 1。"""


class UsageError(Exception):
    """参数错误（不认识的 shell），退出 2，不动任何文件。"""


class Target(NamedTuple):
    shell: str
    path: str
    # 只有 PowerShell 有：该宿主的执行策略，决定不存在的 profile 能不能新建
    policy: Optional[str] = None


class Outcome(NamedTuple):
    """一行输出：status 为 None 时只有说明；error 不为空时是失败。"""
    status: Optional[str]
    path: str
    note: Optional[str] = None
    error: Optional[str] = None


def _system() -> str:
    return py_platform.system()


def _home() -> str:
    return os.path.expanduser("~")


def off_marker_path() -> str:
    return os.path.join(platform.state_dir(), OFF_FILE)


def detect_shell(environ: Mapping[str, str]) -> Optional[str]:
    """未指定 shell 时用：Windows 一律 powershell，其它系统看 $SHELL 的文件名，不认识就返回 None。"""
    if platform.IS_WINDOWS:
        return "powershell"
    name = os.path.basename(environ.get("SHELL") or "")
    return name if name in completion.SHELLS else None


def _zshrc(environ: Mapping[str, str]) -> str:
    return os.path.join(environ.get("ZDOTDIR") or _home(), ".zshrc")


def _bash_rc() -> str:
    # 与 shellpath.py 同一张表：macOS 的终端开的是登录 shell，读 .bash_profile
    return os.path.join(_home(), ".bash_profile" if _system() == "Darwin" else ".bashrc")


def _fish_file(environ: Mapping[str, str]) -> str:
    base = environ.get("XDG_CONFIG_HOME") or os.path.join(_home(), ".config")
    return os.path.join(base, "fish", "completions", "multi-claude.fish")


def _parse_powershell_query(text: str) -> Optional[Tuple[str, str]]:
    """查询输出的第一行非空内容是 $PROFILE，第二行是执行策略；不够两行返回 None。"""
    lines = [line.strip() for line in text.lstrip("\ufeff").splitlines() if line.strip()]
    if len(lines) < 2:
        return None
    return lines[0], lines[1]


def _query_powershell(host: str) -> Optional[Tuple[str, str]]:
    """启动一次该宿主，取它的 $PROFILE 和执行策略；程序不存在或查询失败返回 None（调用方跳过这个宿主）。"""
    if host == "powershell":
        program = platform.system_program("powershell.exe") if platform.IS_WINDOWS else None
    else:
        program = platform.which("pwsh")
    if not program or not os.path.isfile(program):
        return None
    # 父进程临时设的执行策略（PSExecutionPolicyPreference）不能带进来，否则查到的不是用户平时窗口的策略。
    # Windows 的环境变量名不分大小写，按大写比较
    env = {key: value for key, value in os.environ.items() if key.upper() != "PSEXECUTIONPOLICYPREFERENCE"}
    try:
        proc = subprocess.run([program, "-NoProfile", "-NonInteractive", "-Command", _PS_QUERY],
                              stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                              env=env, timeout=POWERSHELL_TIMEOUT)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None
    return _parse_powershell_query(proc.stdout.decode("utf-8", "replace"))


def targets(shell: Optional[str], uninstall: bool, auto: bool,
            environ: Mapping[str, str]) -> List[Target]:
    """要处理的文件。install.sh 卸载（uninstall + auto）时不看 $SHELL，清理全部候选，换过 shell 的用户也清得干净。"""
    if uninstall and auto:
        home = _home()
        return [Target("zsh", _zshrc(environ)),
                Target("bash", os.path.join(home, ".bashrc")),
                Target("bash", os.path.join(home, ".bash_profile")),
                Target("fish", _fish_file(environ))]
    if shell == "zsh":
        return [Target("zsh", _zshrc(environ))]
    if shell == "bash":
        return [Target("bash", _bash_rc())]
    if shell == "fish":
        return [Target("fish", _fish_file(environ))]
    found = []
    for host in POWERSHELL_HOSTS:
        result = _query_powershell(host)
        if result is not None:
            found.append(Target("powershell", result[0], result[1]))
    return found


def _resolve_exe(environ: Mapping[str, str], existing: Optional[str]) -> Optional[str]:
    """块里兜底用的绝对路径：MULTI_CLAUDE_BIN（install.sh 设）→ PATH 上找到的 → 已有块里的。

    兜底路径是为了 PATH 设置排在块后面的情况（install.sh 提示用户追加 PATH 时就是这样）。
    路径里有单引号时写不进单引号串，放弃兜底。
    """
    exe = environ.get("MULTI_CLAUDE_BIN")
    if exe:
        exe = os.path.abspath(exe)
    else:
        exe = platform.which("multi-claude") or existing
    if not exe or "'" in exe:
        return None
    return exe


def block_lines(shell: str, exe: Optional[str]) -> List[str]:
    """块的全部行（含开始、结束标记）。命令找不到、zsh 没初始化补全时，打开终端都不能报错。"""
    if shell == "zsh":
        body = ["_mc_bin=${{commands[multi-claude]:-'{}'}}".format(exe or ""),
                "if [[ -x $_mc_bin ]]; then",
                "  (( $+functions[compdef] )) || { autoload -Uz compinit && compinit -i; }",
                "  eval \"$(\"$_mc_bin\" completion zsh)\"",
                "fi",
                "unset _mc_bin"]
    elif shell == "bash":
        fallback = " || echo '{}'".format(exe) if exe else ""
        body = ["_mc_bin=$(command -v multi-claude 2>/dev/null{})".format(fallback),
                "[ -x \"$_mc_bin\" ] && eval \"$(\"$_mc_bin\" completion bash)\"; unset _mc_bin"]
    else:
        body = [POWERSHELL_LINE]
    return [BEGIN] + body + [END]


def _existing_fallback(shell: str, lines: List[str]) -> Optional[str]:
    pattern = _ZSH_FALLBACK if shell == "zsh" else _BASH_FALLBACK
    for line in lines:
        # 去掉行尾再匹配：CRLF 文件的 \r 会挡住正则末尾的 $，兜底路径就被悄悄丢掉
        match = pattern.search(_content(line))
        if match and match.group(1):
            return match.group(1)
    return None


def _read(path: str) -> Optional[Tuple[bool, str]]:
    """按字节读；返回 (有无 BOM, 文本)，文件不存在返回 None。

    含 NUL 的按非 UTF-8 处理：不带 BOM 的 UTF-16 文件按 UTF-8 也可能“解得开”，改了就坏了。
    """
    try:
        with open(path, "rb") as handle:
            data = handle.read()
    except FileNotFoundError:
        return None
    bom = data.startswith(_UTF8_BOM)
    if bom:
        data = data[len(_UTF8_BOM):]
    if b"\x00" in data:
        raise ShellrcError(_NOT_UTF8)
    try:
        return bom, data.decode("utf-8")
    except UnicodeDecodeError:
        raise ShellrcError(_NOT_UTF8)


def _split(text: str) -> List[str]:
    # 只按 \n 切，每行保留自己的结尾（\n 或 \r\n），拼回去与原文逐字节相同
    return re.findall(r"[^\n]*\n|[^\n]+$", text)


def _content(line: str) -> str:
    return line.rstrip("\r\n")


def _find_block(lines: List[str]) -> Optional[Tuple[int, int]]:
    begins = [i for i, line in enumerate(lines) if _content(line).strip() == BEGIN]
    ends = [i for i, line in enumerate(lines) if _content(line).strip() == END]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or begins[0] > ends[0]:
        raise ShellrcError("the multi-claude completion block is damaged (unpaired or repeated markers); "
                           "fix it by hand and try again")
    return begins[0], ends[0]


def _has_live_call(lines: List[str]) -> bool:
    for line in lines:
        stripped = _content(line).lstrip()
        if not stripped.startswith("#") and _LIVE_CALL.search(stripped):
            return True
    return False


def _write(given: str, real: str, existed: bool, bom: bool, text: str) -> None:
    """改已有文件先备份（备份放在用户给的路径旁边），再按原权限原子写回真实目标。"""
    if existed:
        mode = stat.S_IMODE(os.stat(real).st_mode)
        shutil.copy2(real, _backup_path(given))
    else:
        mode = 0o644
    atomic_write_bytes(real, (_UTF8_BOM if bom else b"") + text.encode("utf-8"), mode)


def _install_block(target: Target, environ: Mapping[str, str]) -> Outcome:
    real = os.path.realpath(target.path)
    loaded = _read(real)
    if loaded is None:
        skip = _skip_new_file(target)
        if skip:
            return Outcome("skipped", target.path, skip)
        bom, text = False, ""
    else:
        bom, text = loaded
        if target.shell == "powershell" and (target.policy or "").lower() == "allsigned":
            return Outcome("skipped", target.path, "the execution policy is AllSigned; changing a signed profile "
                                                   "would break its signature")
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = _split(text)
    found = _find_block(lines)
    exe = _resolve_exe(environ, _existing_fallback(target.shell, lines[found[0]:found[1] + 1]) if found else None)
    block = [line + newline for line in block_lines(target.shell, exe)]
    if found is not None:
        begin, end = found
        if not lines[end].endswith("\n"):
            # 原来的结束标记在文件最后一行、没有换行：照原样不补
            block[-1] = block[-1][:-len(newline)]
        new_lines = lines[:begin] + block + lines[end + 1:]
        if new_lines == lines:
            return Outcome("unchanged", target.path)
        _write(target.path, real, True, bom, "".join(new_lines))
        return Outcome("updated", target.path)
    if _has_live_call(lines):
        return Outcome("present", target.path, "this file already generates the completion when a shell starts; "
                                               "left unchanged")
    note = None
    if _SNAPSHOT in text:
        note = ("this file also holds an old pasted copy of the completion script; the new setup overrides it, "
                "you can delete the old copy")
    if text and not text.endswith("\n"):
        text += newline
    if text:
        text += newline
    _write(target.path, real, loaded is not None, bom, text + "".join(block))
    return Outcome("installed", target.path, note)


def _skip_new_file(target: Target) -> Optional[str]:
    """新建反而会出问题的情况，返回说明；可以新建时返回 None。"""
    home = _home()
    if (target.shell == "bash" and _system() == "Darwin"
            and os.path.basename(target.path) == ".bash_profile"
            and any(os.path.lexists(os.path.join(home, name)) for name in (".bash_login", ".profile"))):
        # bash 登录 shell 只读三个文件里第一个存在的；新建 .bash_profile 会让用户原来那份失效
        return ("~/.bash_profile does not exist and bash reads ~/.bash_login or ~/.profile instead; add this line "
                "to your bash profile by hand: eval \"$(multi-claude completion bash)\"")
    if target.shell == "powershell" and (target.policy or "").lower() in ("restricted", "allsigned"):
        # 执行策略不允许运行脚本时，新建的 profile 每次打开窗口都会报“禁止运行脚本”
        return "the execution policy is {}, so PowerShell would refuse to run a new profile".format(target.policy)
    return None


def _install_fish(target: Target) -> Outcome:
    real = os.path.realpath(target.path)
    loaded = _read(real)
    content = FISH_MARKER + "\n" + FISH_LINE + "\n"
    if loaded is None:
        _write(target.path, real, False, False, content)
        return Outcome("installed", target.path)
    bom, text = loaded
    lines = _split(text)
    first = _content(lines[0]) if lines else ""
    if first == FISH_MARKER:
        if text == content and not bom:
            return Outcome("unchanged", target.path)
        _write(target.path, real, True, False, content)
        return Outcome("updated", target.path)
    if "generated by" in first:
        _write(target.path, real, True, False, content)
        return Outcome("updated", target.path, "replaced an old copy of the completion script")
    return Outcome("present", target.path, "this is your own file; left unchanged")


def _uninstall_one(target: Target) -> Outcome:
    real = os.path.realpath(target.path)
    loaded = _read(real)
    if loaded is None:
        return Outcome("absent", target.path)
    bom, text = loaded
    lines = _split(text)
    if target.shell == "fish":
        if lines and _content(lines[0]) == FISH_MARKER:
            shutil.copy2(real, _backup_path(target.path))
            os.remove(real)
            return Outcome("removed", target.path)
        if text.strip():
            return Outcome("present", target.path, "this is your own file; left unchanged")
        return Outcome("absent", target.path)
    found = _find_block(lines)
    if found is None:
        return Outcome("absent", target.path)
    begin, end = found
    # 连同安装时在块前加的那个空行一起删，反复安装、卸载不会越积越多
    if begin > 0 and _content(lines[begin - 1]).strip() == "":
        begin -= 1
    _write(target.path, real, True, bom, "".join(lines[:begin] + lines[end + 1:]))
    return Outcome("removed", target.path)


def _process(target: Target, uninstall: bool, environ: Mapping[str, str]) -> Outcome:
    try:
        if uninstall:
            return _uninstall_one(target)
        if target.shell == "fish":
            return _install_fish(target)
        return _install_block(target, environ)
    except ShellrcError as exc:
        return Outcome(None, target.path, error=str(exc))
    except OSError as exc:
        return Outcome(None, target.path, error=exc.strerror or str(exc))


def _no_powershell() -> Outcome:
    return Outcome(None, "$PROFILE", error="no PowerShell found (looked for powershell.exe and pwsh)")


def _exit_code(outcomes: List[Outcome]) -> int:
    return 1 if any(item.error for item in outcomes) else 0


def _unknown_shell(environ: Mapping[str, str]) -> str:
    return "cannot tell which shell you use (SHELL={}); name it, e.g. multi-claude completion --install zsh".format(
        environ.get("SHELL") or "not set")


def install(shell: Optional[str], auto: bool, environ: Mapping[str, str]) -> Tuple[List[Outcome], int]:
    """安装。auto 是 install.sh 调用：用户关掉过就跳过，认不出 shell 只给说明、不算错。"""
    off = off_marker_path()
    if auto and os.path.exists(off):
        return [Outcome("skipped-off", off)], 0
    shell = shell or detect_shell(environ)
    if shell is None:
        if auto:
            return [Outcome(None, "", _unknown_shell(environ))], 0
        raise UsageError(_unknown_shell(environ))
    outcomes = []
    if not auto:
        # 用户主动安装，表示又想要了：去掉关闭标记，以后 install.sh 照常维护
        try:
            os.remove(off)
        except FileNotFoundError:
            pass
        except OSError as exc:
            outcomes.append(Outcome(None, off, error=exc.strerror or str(exc)))
    found = targets(shell, False, auto, environ)
    if not found:
        outcomes.append(_no_powershell())
    outcomes.extend(_process(target, False, environ) for target in found)
    return outcomes, _exit_code(outcomes)


def uninstall(shell: Optional[str], auto: bool, environ: Mapping[str, str]) -> Tuple[List[Outcome], int]:
    """卸载。不带 auto 时留下关闭标记，install.sh 以后不再加回；auto（install.sh 卸载）不碰这个标记。"""
    if not auto:
        shell = shell or detect_shell(environ)
        if shell is None:
            raise UsageError(_unknown_shell(environ))
    found = targets(shell, True, auto, environ)
    outcomes = [] if found else [_no_powershell()]
    outcomes.extend(_process(target, True, environ) for target in found)
    if not auto:
        # 与各文件的结果无关：用户的意思是“不要补全”，即使某个文件没改成也要记住
        off = off_marker_path()
        try:
            os.makedirs(os.path.dirname(off), exist_ok=True)
            with open(off, "w"):
                pass
        except OSError as exc:
            outcomes.append(Outcome(None, off, error=exc.strerror or str(exc)))
    return outcomes, _exit_code(outcomes)
