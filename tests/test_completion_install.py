"""方案 feature-auto-completion §8 第 1-14、20-24 条：`completion --install / --uninstall` 改写 shell 配置文件。"""

import os
import shutil
import stat
import subprocess
import sys
import unittest
from unittest import mock

from helpers import SRC, CliTestCase, posix_only

sys.path.insert(0, SRC)
from multi_claude import shellrc  # noqa: E402

BEGIN = shellrc.BEGIN
END = shellrc.END


def read_bytes(path):
    with open(path, "rb") as handle:
        return handle.read()


def write_bytes(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(data)
    return path


@posix_only
class CompletionInstallTest(CliTestCase):
    def setUp(self):
        super().setUp()
        self.zshrc = os.path.join(self.home, ".zshrc")
        self.bin_path = os.path.join(self.tmp, "bin", "multi-claude")
        # 不让开发机或 CI 上真实的 multi-claude 混进来：PATH 只留假程序目录和系统目录
        self.env["SHELL"] = "/bin/zsh"

    def cli(self, *args, env=None):
        return self.run_cli("completion", *args, env=env)

    def backups(self, directory, name):
        return [entry for entry in os.listdir(directory) if entry.startswith(name + ".multi-claude-bak.")]

    def test_zsh_install_keeps_content_and_backs_up(self):  # 第 1 条
        write_bytes(self.zshrc, b"export A=1\n")
        result = self.cli("--install")
        self.assertEqual(result.code, 0, result)
        self.assertIn("completion: installed", result.out)
        data = read_bytes(self.zshrc).decode()
        self.assertTrue(data.startswith("export A=1\n\n" + BEGIN + "\n"))
        self.assertTrue(data.endswith(END + "\n"))
        self.assertEqual(len(self.backups(self.home, ".zshrc")), 1)
        again = self.cli("--install")
        self.assertIn("completion: unchanged", again.out)

    def test_zdotdir(self):  # 第 2 条
        zdot = os.path.join(self.tmp, "zdot")
        result = self.cli("--install", env={"ZDOTDIR": zdot})
        self.assertEqual(result.code, 0, result)
        self.assertIn(BEGIN, read_bytes(os.path.join(zdot, ".zshrc")).decode())
        self.assertFalse(os.path.exists(self.zshrc))

    def test_bash_profile_by_system(self):  # 第 3 条
        result = self.cli("--install", "bash", env={"MULTI_CLAUDE_BIN": self.bin_path})
        self.assertEqual(result.code, 0, result)
        name = ".bash_profile" if sys.platform == "darwin" else ".bashrc"
        text = read_bytes(os.path.join(self.home, name)).decode()
        self.assertIn("|| echo '{}'".format(self.bin_path), text)

    def test_fish_file(self):  # 第 4 条
        fish = os.path.join(self.home, ".config", "fish", "completions", "multi-claude.fish")
        result = self.cli("--install", "fish")
        self.assertEqual(result.code, 0, result)
        self.assertEqual(read_bytes(fish).decode(), shellrc.FISH_MARKER + "\n" + shellrc.FISH_LINE + "\n")
        # 旧快照：备份后替换
        snapshot = "# fish completion for multi-claude (generated by `multi-claude completion fish`)\ncomplete -c x\n"
        write_bytes(fish, snapshot.encode())
        result = self.cli("--install", "fish")
        self.assertIn("completion: updated", result.out)
        self.assertTrue(read_bytes(fish).decode().startswith(shellrc.FISH_MARKER))
        self.assertEqual(len(self.backups(os.path.dirname(fish), "multi-claude.fish")), 1)
        # 用户自己的文件：不动，卸载也不删
        write_bytes(fish, b"complete -c multi-claude -f\n")
        result = self.cli("--install", "fish")
        self.assertIn("completion: present", result.out)
        self.assertEqual(read_bytes(fish), b"complete -c multi-claude -f\n")
        self.assertIn("completion: present", self.cli("--uninstall", "fish").out)
        self.assertEqual(read_bytes(fish), b"complete -c multi-claude -f\n")

    def test_live_call_and_snapshot(self):  # 第 5、22 条
        write_bytes(self.zshrc, b'eval "$(multi-claude completion zsh)"\n')
        result = self.cli("--install")
        self.assertIn("completion: present", result.out)
        self.assertEqual(read_bytes(self.zshrc), b'eval "$(multi-claude completion zsh)"\n')
        snapshot = b"# zsh completion for multi-claude (generated by `multi-claude completion zsh`)\ncompdef x y\n"
        write_bytes(self.zshrc, snapshot)
        result = self.cli("--install")
        self.assertIn("completion: installed", result.out)
        self.assertIn("completion: note:", result.out)
        commented = b'# eval "$(multi-claude completion zsh)"\n'
        write_bytes(self.zshrc, commented)
        self.assertIn("completion: installed", self.cli("--install").out)
        bashrc = os.path.join(self.home, ".bash_profile" if sys.platform == "darwin" else ".bashrc")
        write_bytes(bashrc, b"source <(multi-claude completion bash)\n")
        self.assertIn("completion: present", self.cli("--install", "bash").out)

    def run_shell(self, argv, script, env):
        return subprocess.run(argv + ["-c", script], env=env, stdin=subprocess.DEVNULL,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True, timeout=60)

    def wrapper(self):
        # 一个可执行的 multi-claude：用测试用的源码目录运行
        self.write(self.bin_path, '#!/bin/sh\nPYTHONPATH="{}" exec "{}" -m multi_claude "$@"\n'.format(
            SRC, sys.executable), 0o755)

    def shell_env(self, path):
        return {"HOME": self.home, "PATH": path, "TERM": "dumb", "ZDOTDIR": self.home}

    @unittest.skipUnless(shutil.which("zsh"), "zsh is not installed")
    def test_zsh_live(self):  # 第 6 条
        system_path = "/usr/bin:/bin"
        # 没有命令、也没有兜底路径：静默
        self.cli("--install")
        proc = self.run_shell(["zsh", "-f", "-i"], "source ~/.zshrc", self.shell_env(system_path))
        self.assertEqual((proc.returncode, proc.stdout, proc.stderr), (0, "", ""))
        # 兜底路径 + PATH 设置排在块后面、没有 compinit：照样注册
        self.wrapper()
        os.remove(self.zshrc)
        self.cli("--install", env={"MULTI_CLAUDE_BIN": self.bin_path})
        with open(self.zshrc, "a") as handle:
            handle.write('export PATH="{}:$PATH"\n'.format(os.path.dirname(self.bin_path)))
        proc = self.run_shell(["zsh", "-f", "-i"], "source ~/.zshrc; print -r -- ${_comps[multi-claude]}",
                              self.shell_env(system_path))
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertTrue(proc.stdout.strip(), proc.stderr)

    @unittest.skipUnless(shutil.which("bash"), "bash is not installed")
    def test_bash_live(self):  # 第 6 条
        system_path = "/usr/bin:/bin"
        rc = os.path.join(self.home, ".bash_profile" if sys.platform == "darwin" else ".bashrc")
        self.cli("--install", "bash")
        proc = self.run_shell(["bash", "--norc", "-i"], "source " + rc, self.shell_env(system_path))
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(proc.stdout, "")
        self.wrapper()
        os.remove(rc)
        self.cli("--install", "bash", env={"MULTI_CLAUDE_BIN": self.bin_path})
        proc = self.run_shell(["bash", "--norc", "-i"], "source {}; complete -p multi-claude".format(rc),
                              self.shell_env(system_path))
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("multi-claude", proc.stdout)

    def test_uninstall_writes_off_marker(self):  # 第 7 条
        write_bytes(self.zshrc, b"a\n")
        self.cli("--install")
        result = self.cli("--uninstall")
        self.assertEqual(result.code, 0, result)
        self.assertEqual(read_bytes(self.zshrc), b"a\n")
        off = os.path.join(self.state, "completion-off")
        self.assertTrue(os.path.exists(off))
        auto = self.cli("--install", "--auto")
        self.assertIn("completion: skipped-off", auto.out)
        self.assertEqual(read_bytes(self.zshrc), b"a\n")
        self.assertIn("completion: installed", self.cli("--install").out)
        self.assertFalse(os.path.exists(off))

    def test_damaged_block(self):  # 第 8 条
        for content in (BEGIN + "\nx\n", BEGIN + "\n" + END + "\n" + BEGIN + "\n" + END + "\n"):
            with self.subTest(content=content):
                write_bytes(self.zshrc, content.encode())
                result = self.cli("--install")
                self.assertEqual(result.code, 1, result)
                self.assertIn("damaged", result.err)
                self.assertEqual(read_bytes(self.zshrc), content.encode())

    def test_unknown_shell(self):  # 第 9 条
        for shell in (None, "/bin/tcsh"):
            with self.subTest(shell=shell):
                env = {"SHELL": shell}
                self.assertEqual(self.cli("--install", env=env).code, 2)
                self.assertEqual(self.cli("--uninstall", env=env).code, 2)
                self.assertFalse(os.path.exists(os.path.join(self.state, "completion-off")))
                auto = self.cli("--install", "--auto", env=env)
                self.assertEqual(auto.code, 0, auto)
                self.assertIn("completion: note:", auto.out)
        self.assertEqual(self.cli().code, 2)

    def test_symlink_and_mode(self):  # 第 10、24 条
        dotfiles = os.path.join(self.tmp, "dotfiles")
        target = write_bytes(os.path.join(dotfiles, "zshrc"), b"a\n")
        os.symlink(target, self.zshrc)
        self.assertEqual(self.cli("--install").code, 0)
        self.assertTrue(os.path.islink(self.zshrc))
        self.assertIn(BEGIN.encode(), read_bytes(target))
        self.assertEqual(len(self.backups(self.home, ".zshrc")), 1)
        self.assertEqual(os.listdir(dotfiles), ["zshrc"])
        os.remove(self.zshrc)
        write_bytes(self.zshrc, b"a\n")
        os.chmod(self.zshrc, 0o600)
        self.cli("--install")
        self.assertEqual(stat.S_IMODE(os.stat(self.zshrc).st_mode), 0o600)

    def test_auto_uninstall_cleans_every_candidate(self):  # 第 11 条
        self.cli("--install")
        off = self.write(os.path.join(self.state, "completion-off"), "")
        bashrc = write_bytes(os.path.join(self.home, ".bashrc"), (BEGIN + "\n").encode())
        result = self.cli("--uninstall", "--auto", env={"SHELL": None})
        self.assertEqual(result.code, 1, result)
        self.assertNotIn(BEGIN, read_bytes(self.zshrc).decode())
        self.assertEqual(read_bytes(bashrc), (BEGIN + "\n").encode())
        self.assertTrue(os.path.exists(off))
        os.remove(off)
        os.remove(bashrc)
        self.cli("--install")
        self.assertEqual(self.cli("--uninstall", "--auto", env={"SHELL": None}).code, 0)
        self.assertFalse(os.path.exists(off))

    def test_bytes_are_preserved(self):  # 第 12 条
        original = b"\xef\xbb\xbfexport A=1\r\necho \xe4\xb8\xad\r\n"
        write_bytes(self.zshrc, original)
        self.cli("--install")
        data = read_bytes(self.zshrc)
        self.assertTrue(data.startswith(b"\xef\xbb\xbf"))
        self.assertIn((BEGIN + "\r\n").encode(), data)
        self.assertNotIn(b"\r\r\n", data)
        self.cli("--uninstall")
        self.assertEqual(read_bytes(self.zshrc), original)
        for bad in ("中文".encode("gbk") + b"\n", b"a\x00b\n"):
            with self.subTest(bad=bad):
                write_bytes(self.zshrc, bad)
                result = self.cli("--install")
                self.assertEqual(result.code, 1, result)
                self.assertIn("UTF-8", result.err)
                self.assertEqual(read_bytes(self.zshrc), bad)

    def test_round_trip(self):  # 第 13 条
        for original, expected in ((b"a\nb\n", b"a\nb\n"), (b"", b""), (b"a", b"a\n")):
            with self.subTest(original=original):
                write_bytes(self.zshrc, original)
                for _ in range(3):
                    self.cli("--install")
                    self.cli("--uninstall")
                self.assertEqual(read_bytes(self.zshrc), expected)
        for original in (b"", b"a\r\n"):
            with self.subTest(fallback=original):
                write_bytes(self.zshrc, original)
                self.cli("--install", env={"MULTI_CLAUDE_BIN": self.bin_path})
                again = self.cli("--install")
                self.assertIn("completion: unchanged", again.out)
                self.assertIn("'{}'".format(self.bin_path), read_bytes(self.zshrc).decode())

    def test_fish_marker_with_old_content(self):  # 第 23 条
        fish = write_bytes(os.path.join(self.home, ".config", "fish", "completions", "multi-claude.fish"),
                           (shellrc.FISH_MARKER + "\nold line\n").encode())
        self.assertIn("completion: updated", self.cli("--install", "fish").out)
        self.assertIn(shellrc.FISH_LINE, read_bytes(fish).decode())
        write_bytes(fish, (shellrc.FISH_MARKER + "\nold line\n").encode())
        self.assertIn("completion: removed", self.cli("--uninstall", "fish").out)
        self.assertFalse(os.path.exists(fish))


class InProcessTest(unittest.TestCase):
    """进程内调用 shellrc：替换系统判断与 PowerShell 查询，所有平台都能跑。"""

    def setUp(self):
        import tempfile
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.home = os.path.join(self.tmp, "home")
        os.makedirs(self.home)
        env = {"HOME": self.home, "USERPROFILE": self.home, "XDG_CONFIG_HOME": os.path.join(self.home, ".config"),
               "APPDATA": os.path.join(self.home, "AppData")}
        patcher = mock.patch.dict(os.environ, env)
        patcher.start()
        self.addCleanup(patcher.stop)
        self.environ = {}

    def test_macos_bash_without_bash_profile(self):  # 第 14 条
        write_bytes(os.path.join(self.home, ".profile"), b"x\n")
        with mock.patch.object(shellrc, "_system", return_value="Darwin"):
            outcomes, code = shellrc.install("bash", False, self.environ)
        self.assertEqual(code, 0)
        self.assertEqual(outcomes[0].status, "skipped")
        self.assertFalse(os.path.exists(os.path.join(self.home, ".bash_profile")))
        outcomes, code = shellrc.install("fish", False, self.environ)
        self.assertEqual((outcomes[0].status, code), ("installed", 0))

    def query(self, results):
        return mock.patch.object(shellrc, "_query_powershell", side_effect=lambda host: results.get(host))

    def test_powershell(self):  # 第 20 条
        five = os.path.join(self.tmp, "文档", "WindowsPowerShell", "Microsoft.PowerShell_profile.ps1")
        seven = os.path.join(self.tmp, "docs", "PowerShell", "Microsoft.PowerShell_profile.ps1")
        results = {"powershell": (five, "RemoteSigned"), "pwsh": (seven, "RemoteSigned")}
        with self.query(results):
            outcomes, code = shellrc.install("powershell", False, self.environ)
            self.assertEqual(code, 0, outcomes)
            for path in (five, seven):
                self.assertIn(shellrc.POWERSHELL_LINE.encode(), read_bytes(path))
            # 一个是 UTF-16：它失败、另一个照常
            utf16 = "x\r\n".encode("utf-16-le")
            write_bytes(five, utf16)
            os.remove(seven)
            outcomes, code = shellrc.install("powershell", False, self.environ)
            self.assertEqual(code, 1)
            self.assertEqual(read_bytes(five), utf16)
            self.assertTrue(os.path.exists(seven))
            outcomes, code = shellrc.uninstall("powershell", False, self.environ)
            self.assertNotIn(shellrc.BEGIN.encode(), read_bytes(seven))
        os.remove(seven)
        with self.query({"pwsh": (seven, "Restricted")}):
            outcomes, code = shellrc.install("powershell", False, self.environ)
            self.assertEqual((outcomes[0].status, code), ("skipped", 0))
            self.assertFalse(os.path.exists(seven))
        # 已有的 profile、执行策略 AllSigned：改了会让签名失效，跳过
        write_bytes(seven, b"# signed\r\n")
        with self.query({"pwsh": (seven, "AllSigned")}):
            outcomes, code = shellrc.install("powershell", False, self.environ)
            self.assertEqual((outcomes[0].status, code), ("skipped", 0))
            self.assertEqual(read_bytes(seven), b"# signed\r\n")
        with self.query({}):
            outcomes, code = shellrc.install("powershell", False, self.environ)
            self.assertEqual(code, 1)

    def test_parse_query(self):  # 第 21 条
        text = "\ufeffC:\\Users\\张三\\Documents\\profile.ps1\r\nRemoteSigned\r\n"
        self.assertEqual(shellrc._parse_powershell_query(text),
                         ("C:\\Users\\张三\\Documents\\profile.ps1", "RemoteSigned"))
        self.assertIsNone(shellrc._parse_powershell_query("only one line\r\n"))


